"""Write the source-review packet docs/data/published-review.md from the candidate records.

    python data/tools/review_table.py

Regenerate after every rebuild. The "automated consistency checks" are recomputed here from the
cached PMC XML; they are not a source review. The human review section is left blank.
"""
from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import pmc_fetch  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
CAND = ROOT / "data" / "published" / "candidates"
LICENCE = ROOT / "data" / "published" / "licence-checks.json"
OUT = ROOT / "docs" / "data" / "published-review.md"


def cell(text: str, limit: int = 0) -> str:
    text = text.replace("|", "\\|")
    return text if not limit or len(text) <= limit else text[: limit - 1] + "…"


def automated_checks(r: dict) -> list[tuple[str, bool]]:
    pmcid = r["article_identifiers"]["pmcid"]
    xml = pmc_fetch.fetch_xml(pmcid)
    paras = {loc: t for loc, _, t in pmc_fetch.paragraphs(xml)}
    meta = pmc_fetch.metadata(xml)
    own = {p["passage_id"]: p["text"] for p in r["passages"]}
    refs = [e for group in ("features", "actions", "outcomes") for item in r[group] for e in item["evidence"]]
    xml_sha = hashlib.sha256(xml.read_bytes()).hexdigest()

    def verbatim(p: dict) -> bool:
        loc = p["locator"].split("(")[1].split(" of the JATS")[0]
        start, end = (int(x) for x in p["locator"].rsplit("characters ", 1)[1].split("-"))
        return paras.get(loc, "")[start:end] == p["text"]

    return [
        (f"Cached XML matches the recorded artifact hash ({xml_sha[:16]})", r["source_version"].startswith(
            f"pmc-efetch-jats sha256:{xml_sha[:16]}")),
        ("Every passage is verbatim at its stated paragraph and character range", all(map(verbatim, r["passages"]))),
        ("Every passage SHA-256 matches its text",
         all(hashlib.sha256(p["text"].encode()).hexdigest() == p["sha256"] for p in r["passages"])),
        ("Every passage belongs to this case", all(p["case_id"] == r["case_id"] for p in r["passages"])),
        ("Every quote is inside a passage of this case",
         all(e["source_type"] == "case_passage" and e["quote"] in own.get(e["source_id"], "") for e in refs)),
        ("Title, authors, journal and year equal the XML metadata",
         (r["title"], r["citation"]["authors"], r["citation"]["journal"], r["citation"]["year"])
         == (meta["title"], meta["authors"], meta["journal"], meta["year"])),
        ("Licence equals the XML ali:license_ref", r["citation"]["license_url"] == meta["license_ali_ref"]),
        ("Every symptom–site association names an affirmed symptom and site feature of this case",
         all({("symptom", f["value"].split("@")[0]), ("site", f["value"].split("@")[1])}
             <= {(g["key"], g["value"]) for g in r["features"] if g["polarity"] == "affirmed"}
             for f in r["features"] if f["key"] == "symptom_site")),
        ("Source review is pending and clinical review is false",
         r["source_review"] == {"status": "pending", "reviewer": None, "reviewed_at": None}
         and r["clinical_reviewed"] is False),
    ]


def main() -> int:
    notes = {n["case_id"]: n for n in json.loads((CAND / "review-notes.json").read_text(encoding="utf-8"))}
    licences = {c["pmcid"]: c for c in json.loads(LICENCE.read_text(encoding="utf-8"))}
    lines = [
        "# Published case candidates: source-review packet",
        "",
        "Generated by `data/tools/review_table.py` from `data/published/candidates/`. Do not edit by hand.",
        "",
        "Both records are **pending source review**, and **neither has had clinical review**. Pending records",
        "are excluded from published retrieval (`unreviewed_source`) and cannot be imported.",
        "",
        "**To review a case:**",
        "",
        "1. Open the article and confirm the patient, every passage, quote and locator, the licence, and the",
        "   proposed features, actions and outcomes. Resolve or accept each flag.",
        "2. Record the result in the review table at the end of that case's section.",
        "3. Only after your own review, run",
        "   `python data/tools/record_source_review.py <case_id> --reviewer \"Name\" --i-checked-the-article`.",
        "",
        "If a case needs corrections, they are made in `build_published_candidates.py`; then the case is",
        "rebuilt and reviewed again.",
        "",
    ]
    for path in sorted(CAND.glob("PUB-*.json")):
        r = json.loads(path.read_text(encoding="utf-8"))
        n = notes[r["case_id"]]
        ids, cite = r["article_identifiers"], r["citation"]
        lic = licences.get(ids["pmcid"], {})
        pdf = lic.get("publisher_pdf", {})
        short = {p["passage_id"]: p["passage_id"].rsplit("-", 1)[1] for p in r["passages"]}
        lines += [
            f"## {r['case_id']}",
            "",
            f"**{r['title']}**. {', '.join(cite['authors'])}. *{cite['journal']}* {cite['year']}.",
            "",
            f"- **Article:** <{r['article_url']}>. PMID {ids.get('pmid')}, PMCID {ids['pmcid']}, "
            f"DOI {ids.get('doi')}.",
            f"- **Patient in the report:** {n['patient_in_article']} Discovery record: PMC-Patients "
            f"`{n['pmc_patients_uid']}`, which is not used as a source.",
            "- **Passage source:** PMC JATS XML from E-utilities efetch, "
            f"sha256 `{lic.get('xml', {}).get('sha256', n['xml_sha256'])}`.",
            f"- **Licence carried by the record:** {cite['license_name']} (<{cite['license_url']}>), taken from "
            "the XML `ali:license_ref` and `<license xlink:href>`.",
        ]
        if pdf.get("status") == "retrieved":
            lines.append(f"- **Publisher PDF licence:** “{cell(pdf['licence_statements'][0])}” "
                         f"(<{pdf['url']}>, sha256 `{pdf['sha256'][:16]}…`, not used for passages).")
        else:
            lines.append("- **Publisher PDF licence:** not retrieved, because every route returned a browser "
                         "challenge or 403, and none was bypassed. It is not required: the XML supports both the "
                         "passages and the licence.")
        lines += ["", "### Passages", "", "| ID | Locator | Exact text |", "|---|---|---|"]
        for p in r["passages"]:
            loc = p["locator"].removeprefix(f"{ids['pmcid']} ")
            lines.append(f"| {short[p['passage_id']]} | {cell(loc)} | {cell(p['text'])} |")
        assoc = [f for f in r["features"] if f["key"] == "symptom_site"]
        lines += ["", "### Proposed symptom–site associations (structured-v2 matches only on these)", "",
                  "| Association | Quote stating them together | Passage |", "|---|---|---|"]
        for f in assoc:
            q = f["evidence"][0]
            symptom, site = f["value"].split("@")
            lines.append(f"| {symptom.replace('_', ' ')} on the {site.replace('_', ' ')} | “{cell(q['quote'])}” | "
                         f"{short[q['source_id']]} |")
        lines += ["", "### Other proposed normalized features", "",
                  "| Feature | Quote | Passage |", "|---|---|---|"]
        for f in [f for f in r["features"] if f["key"] != "symptom_site"]:
            q = f["evidence"][0]
            pol = "" if f["polarity"] == "affirmed" else " (negated)"
            lines.append(f"| `{f['key']}` = `{f['value']}`{pol} | “{cell(q['quote'])}” | {short[q['source_id']]} |")
        lines += ["", "Anything the article does not mention is left unrecorded and treated as unknown, never as "
                  "absent."]
        lines += ["", "### Actions and outcomes (shown to the doctor only)", "",
                  "| Kind | Statement | Quotes | Passage |", "|---|---|---|---|"]
        for kind in ("actions", "outcomes"):
            for s in r[kind]:
                quotes = "<br>".join(f"“{cell(e['quote'])}”" for e in s["evidence"])
                pids = ", ".join(sorted({short[e["source_id"]] for e in s["evidence"]}))
                lines.append(f"| {kind[:-1]} | {cell(s['text'])} | {quotes} | {pids} |")
        lines += ["", "### Unresolved flags (for your decision)", ""]
        lines += [f"{i}. {flag}" for i, flag in enumerate(n["review_flags"], 1)]
        lines += ["", "### Automated consistency checks (by the tool; not a source review)", ""]
        lines += [f"- [{'x' if ok else ' '}] {label}{'' if ok else ' FAILED'}" for label, ok in automated_checks(r)]
        lines += ["", "### Human source review (blank until you review)", "",
                  "| Reviewer | Reviewed at (UTC) | Patient correct | Passages and quotes | Features | "
                  "Actions and outcomes | Licence | Decision |",
                  "|---|---|---|---|---|---|---|---|", "|  |  |  |  |  |  |  |  |", ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
